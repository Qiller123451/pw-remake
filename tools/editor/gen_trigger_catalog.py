"""Writes src/Sim/Editor/Triggers/TriggerCatalog.Data.cs: the parameters of every condition and action type with the
original's type (int / string / bool) and default, read from the game's Scripts/Server/misc/condition_attrib_def.txt and
action_attrib_def.txt (the level editor's definitions: a type nested in another inherits its parameters, the root's
own attribs belong to every type). The official game's and MIRAGE's files are merged (MIRAGE's win where both define
a type). The map editor's trigger catalogue (TriggerCatalog.cs) adds the editor's kinds, choices and help to them.

    python3 tools/editor/gen_trigger_catalog.py <Data folder of the installation> [out.cs]
"""
import os
import re
import sys

PAIR = re.compile(r"^(.+?)\s*=\s*(?:'(.*)'|\"(.*)\"|(\S*))\s*(\{)?$")
SKIP = {'renderable', 'renderable_type'}   # the level editor's own (the converter leaves them out too)


def tree(text):
    root = {'name': '', 'attr': {}, 'children': []}
    stack = [root]
    for ln in text.splitlines():
        ln = ln.strip()
        if not ln:
            continue
        if ln == '}':
            stack.pop()
            continue
        m = PAIR.match(ln)
        if m:
            key = m.group(1).strip()
            val = next((g for g in m.group(2, 3, 4) if g is not None), '')
            if m.group(5):
                c = {'name': key, 'attr': {}, 'children': []}
                stack[-1]['children'].append(c)
                stack.append(c)
            else:
                stack[-1]['attr'][key] = val
        elif ln.endswith('{'):
            c = {'name': ln[:-1].strip().strip('"'), 'attr': {}, 'children': []}
            stack[-1]['children'].append(c)
            stack.append(c)
    return root['children'][0]


def types(text):
    out = {}

    def own(n):
        a = next((c for c in n['children'] if c['name'] == 'attribs'), None)
        return [(c['name'], c['attr'].get('type', 'string'), c['attr'].get('default')) for c in a['children']] if a else []

    def merge(base, add):
        d = list(base)
        for k, t, v in add:
            d = [x for x in d if x[0] != k] + [(k, t, v)]
        return d

    def walk(n, inherited):
        mine = merge(inherited, own(n))
        for c in n['children']:
            if c['name'] == 'attribs':
                continue
            out[c['name']] = merge(mine, own(c))
            walk(c, mine)
    walk(tree(text), [])
    return out


def cs(s):
    return 'null' if s is None else '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main(argv):
    data = argv[1]
    out = argv[2] if len(argv) > 2 else os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'Sim', 'Editor', 'Triggers', 'TriggerCatalog.Data.cs')
    res = {}
    for kind in ('condition', 'action'):
        merged = {}
        for folder in ('Base', 'MIRAGE'):
            p = os.path.join(data, folder, 'Scripts', 'Server', 'misc', '%s_attrib_def.txt' % kind)
            if os.path.exists(p):
                merged.update(types(open(p, encoding='latin-1').read()))
        res[kind] = merged
    L = ['// Generated by tools/editor/gen_trigger_catalog.py from the original\'s Scripts/Server/misc/condition_attrib_def.txt and',
         '// action_attrib_def.txt (official game + MIRAGE): every node type\'s parameters - key, the original\'s type, default.',
         '// Do not edit; TriggerCatalog.cs adds the editor\'s kinds, choices and help.',
         'namespace PwRemake.Sim.Editor.Triggers;', '',
         'public static partial class TriggerCatalog', '{',
         '    /// <summary>(condition?, code) -> (key, type, default) in the definition\'s order</summary>',
         '    static readonly (bool Cond, string Code, (string Key, string Type, string? Default)[] Params)[] Defs =', '    {']
    for kind in ('condition', 'action'):
        for code in sorted(res[kind]):
            ps = [p for p in res[kind][code] if p[0] not in SKIP]
            L.append('        (%s, "%s", new (string, string, string?)[] { %s }),' % (
                'true' if kind == 'condition' else 'false', code, ', '.join('(%s, %s, %s)' % (cs(k), cs(t), cs(v)) for k, t, v in ps)))
    L += ['    };', '}', '']
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L))
    print('wrote', out, len(res['condition']), 'conditions', len(res['action']), 'actions')


if __name__ == '__main__':
    main(sys.argv)
